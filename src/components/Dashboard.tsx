import React, { useEffect, useState, useCallback } from "react";
import { Link } from "react-router-dom";
import { Scale, Calculator, Book, Plus, ArrowRight } from "lucide-react";
import { User } from "@supabase/supabase-js";
import { format } from "date-fns";

import { Button } from "@/components/ui/button";
import { supabase } from "@/integrations/supabase/client";
import shore from "@/assets/puppy-journal-shore.webp";
import bookMockup from "@/assets/puppy-journal-books.webp";
import Footer from "@/components/Footer";
import SEO from "@/components/SEO";
import AdBanner from "@/components/AdBanner";

interface DashboardProps {
  user: User;
}

interface Dog {
  id: string;
  name: string;
  age_years?: number | null;
}

interface WeightEntry {
  id: string;
  weight: number;
  date: string;
  created_at: string;
}

const Dashboard: React.FC<DashboardProps> = ({ user }) => {
  const [dogs, setDogs] = useState<Dog[]>([]);
  const [lastWeight, setLastWeight] = useState<WeightEntry | null>(null);
  const [loading, setLoading] = useState(true);
  const [loadError, setLoadError] = useState("");

  const fetchUserData = useCallback(async () => {
    try {
      setLoading(true);
      setLoadError("");
      setLastWeight(null);

      // Fetch dogs
      const { data: dogsData, error: dogsError } = await supabase
        .from("dogs")
        .select("*")
        .eq("user_id", user.id);

      if (dogsError) throw dogsError;

      // Cast to unknown then Dog[] to avoid strict type mismatches with autogenerated types
      setDogs((dogsData as unknown as Dog[]) || []);

      if (dogsData && dogsData.length > 0) {
        // Fetch latest weight for the first dog
        const { data: weightData, error: weightError } = await supabase
          .from("weight_entries")
          .select("*")
          .eq("dog_id", dogsData[0].id)
          .order("date", { ascending: false })
          .limit(1);

        if (weightError) throw weightError;

        if (weightData && weightData.length > 0) {
          setLastWeight(weightData[0] as unknown as WeightEntry);
        }
      }
    } catch (error) {
      console.error("Error fetching dashboard data:", error);
      setLoadError(
        "Pennun tietoja ei voitu hakea. Tarkista yhteys ja yritä uudelleen.",
      );
    } finally {
      setLoading(false);
    }
  }, [user]);

  useEffect(() => {
    fetchUserData();
  }, [fetchUserData]);

  const getGreeting = () => {
    const hour = new Date().getHours();
    return hour < 10
      ? "Hyvää huomenta"
      : hour < 18
        ? "Hyvää päivää"
        : "Hyvää iltaa";
  };
  const measuredAt = lastWeight
    ? new Date(lastWeight.date || lastWeight.created_at)
    : null;
  return (
    <div className="site-page site-dashboard">
      <SEO
        title="Oma Pentulaskuri"
        siteName="Pentulaskuri"
        description="Oman pennun painonseuranta, ruokamäärän arvio ja pentukirja yhdessä paikassa."
      />
      <header className="site-dashboard-header">
        <div>
          <h1>{getGreeting()}.</h1>
          <p>
            {dogs.length > 0 ? (
              <>
                Tässä on pennun <strong>{dogs[0].name}</strong> yhteinen arki:
                mittaukset, ruokinta ja muistot.
              </>
            ) : (
              "Aloita lisäämällä pentusi tiedot. Sen jälkeen voit tallentaa mittauksia ja yhteisiä hetkiä."
            )}
          </p>
        </div>
        <img src={shore} width={1400} height={467} alt="" />
      </header>
      {loading ? (
        <p role="status">Ladataan pennun tietoja…</p>
      ) : loadError ? (
        <div role="alert">
          <p>{loadError}</p>
          <Button className="mt-4" onClick={fetchUserData}>
            Yritä uudelleen
          </Button>
        </div>
      ) : (
        <div className="site-dashboard-overview">
          <section
            className="site-dashboard-weight"
            aria-labelledby="dashboard-weight"
          >
            <h2 id="dashboard-weight">Viimeisin painomittaus</h2>
            {lastWeight ? (
              <>
                <strong>
                  {new Intl.NumberFormat("fi-FI").format(lastWeight.weight)} kg
                </strong>
                <p>
                  {measuredAt && !Number.isNaN(measuredAt.getTime())
                    ? `Mitattu ${format(measuredAt, "d.M.yyyy")}`
                    : "Mittauspäivä puuttuu."}
                </p>
                <Button asChild>
                  <Link to="/weight-tracker">
                    Lisää uusi mittaus <Plus size={18} aria-hidden="true" />
                  </Link>
                </Button>
              </>
            ) : (
              <>
                <p>Ensimmäinen mittaus on hyvä alku omalle kasvun tarinalle.</p>
                <Button asChild>
                  <Link to={dogs.length ? "/weight-tracker" : "/onboarding"}>
                    {dogs.length ? "Lisää ensimmäinen mittaus" : "Lisää pentu"}
                    <ArrowRight size={18} aria-hidden="true" />
                  </Link>
                </Button>
              </>
            )}
          </section>
          <nav className="site-dashboard-links" aria-label="Omat työkalut">
            {[
              {
                icon: Scale,
                title: "Painonseuranta",
                text: "Mittaukset ja kasvun näkymät",
                href: "/weight-tracker",
              },
              {
                icon: Calculator,
                title: "Ruokalaskuri",
                text: "Arvioi ruoka-annosta ja tarkista perusteet",
                href: "/calculator",
              },
              {
                icon: Book,
                title: "Pentukirja",
                text: "Yksi kuva tai muutama sana tästä päivästä",
                href: "/puppy-book",
              },
            ].map(({ icon: Icon, title, text, href }) => (
              <Link to={href} key={href}>
                <Icon size={24} strokeWidth={1.5} aria-hidden="true" />
                <span>
                  <strong>{title}</strong>
                  <small>{text}</small>
                </span>
                <ArrowRight size={18} aria-hidden="true" />
              </Link>
            ))}
          </nav>
        </div>
      )}
      <section className="site-book-feature" aria-labelledby="dashboard-book">
        <img src={bookMockup} width={1200} height={919} alt="" loading="lazy" />
        <div>
          <h2 id="dashboard-book">Mitä tästä päivästä jää kirjaan?</h2>
          <p>
            Tallenna pieni hetki, valitse kirjan ilme ja jatka tarinaa omaan
            tahtiisi.
          </p>
          <Link to="/puppy-book" className="site-link">
            Jatka pentukirjaa <ArrowRight size={18} aria-hidden="true" />
          </Link>
          <p className="text-sm mt-3">
            Kuvitettu esimerkki omaksi PDF-kirjaksi koottavasta pentukirjasta.
          </p>
        </div>
      </section>
      <div className="mt-8 flex justify-center">
        <AdBanner variant="rectangle" className="w-full max-w-sm" />
      </div>
      <Footer compact />
    </div>
  );
};

export default Dashboard;
